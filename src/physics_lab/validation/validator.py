def check_interference(model: Model, result: ModelResult) -> CheckResult:
    """Interference is a separate module; not part of the first prototypes."""
    if result.metadata.get("interference") is None:
        return CheckResult(
            name="Interference",
            status=CheckStatus.UNTESTED,
            message="Interference module is available but not wired into this model.",
        )
    return CheckResult(
        name="Interference",
        status=CheckStatus.PASS,
        message=str(result.metadata.get("interference")),
    )


def check_alpha(model: Model, result: ModelResult) -> CheckResult:
    """Compare alpha only AFTER derivation.  Circle/C3 do not predict alpha."""
    qty = result.quantity("alpha") or result.quantity("alpha_inverse")
    if qty is None:
        return CheckResult(
            name="Alpha prediction",
            status=CheckStatus.UNTESTED,
            message="No alpha_model was produced. The laboratory will not fit 1/137.",
        )

    if qty.provenance.is_prediction_blocker() or qty.free_dependencies:
        # Import experimental value only now, at comparison time.
        from physics_lab.physics import constants as experimental

        ref = experimental.ALPHA_INVERSE
        return CheckResult(
            name="Alpha prediction",
            status=CheckStatus.CALIBRATED,
            message=(
                f"STATUS = {qty.provenance.value}. NOT A PREDICTION. "
                f"alpha_model={qty.value}; experimental reference={ref.value}."
            ),
            details={"alpha_model": qty.value, "alpha_experimental": ref.value},
        )

    from physics_lab.physics import constants as experimental

    ref = experimental.ALPHA_INVERSE
    model_value = qty.numeric()
    rel = abs(model_value - ref.numeric) / abs(ref.numeric)
    status = CheckStatus.PASS if rel < 1e-3 else CheckStatus.FAIL
    return CheckResult(
        name="Alpha prediction",
        status=status,
        message=(
            f"alpha prediction: {model_value}; experimental reference: {ref.value}; "
            f"relative error: {rel:.3e}"
        ),
        details={"relative_error": rel},
    )


