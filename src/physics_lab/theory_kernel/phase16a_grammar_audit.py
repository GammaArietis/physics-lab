def _entry(payload: dict[str, Any]) -> dict[str, Any]:
    payload = dict(payload)
    payload["generator_enabled"] = False
    payload["search_status"] = "NOT_ENABLED"
    missing = [name for name in ENTRY_FIELDS if name not in payload]
    if missing:
        raise KeyError(",".join(missing))
    if payload["search_status"] != "NOT_ENABLED" or payload["generator_enabled"] is not False:
        raise RuntimeError("a catalogue entry cannot enable a generator")
    return payload


