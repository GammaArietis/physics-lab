def _on_frontier(item: dict[str, Any]) -> bool:
    representable = item["current_phase15_representability"] in {"NOT_REPRESENTABLE", "OUTSIDE_DECLARED_WINDOW"}
    questions = item["novelty_test"]
    bounded = item["bounds_required"].get("declaration") == "DECLARED_FOR_FUTURE_USE"
    return (
        item["review_status"] == "READY_FOR_HUMAN_REVIEW"
        and item["structural_class"] == "GENUINELY_NEW_GRAMMAR"
        and representable
        and bounded
        and questions["Q1"] == "NO"
        and questions["Q5"] == "YES"
        and questions["Q6"] == "YES"
        and all(questions[key] != "UNRESOLVED" for key in questions)
    )


