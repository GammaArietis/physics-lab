"""Report for Phase 4B dynamical gravity plus internal sector."""

from __future__ import annotations

from physics_lab.core.result import ModelResult
from physics_lab.reporting.formatting import banner, table


def format_gravity_internal_report(result: ModelResult) -> str:
    data = result.metadata.get("gravity_internal_analysis")
    if not data:
        return ""
    wf = data.get("weak_field") or {}
    a = data.get("massless_mode") or {}
    b = data.get("massive_mode") or {}
    bg = data.get("background_conditions") or {}
    lines = [
        banner("PHASE 4B — DYNAMICAL GRAVITY + INTERNAL SECTOR", width=48),
        "",
        "Dynamical fields:",
        "g_{μν}",
        "χ",
        "",
        "chi status:",
        str(data.get("chi_status")),
        "",
        "Gravity sector:",
        str(data.get("gravity_sector")),
        "",
        "Internal-sector class:",
        str(data.get("internal_sector_class")),
        "",
        "Background:",
        str(data.get("background")),
        f"  chi EOM condition: {bg.get('chi_eom_required')}",
        f"  metric vacuum condition: {bg.get('metric_required')}",
        f"  chi0 forced to zero: {bg.get('chi0_forced_to_zero')}",
        "",
        "Quadratic internal dynamics:",
        str(data.get("quadratic_internal")),
        f"  kinetic coefficient: {data.get('kinetic_coefficient')}",
        "",
        "m_eff²:",
        str(data.get("m_eff2_formula")),
        f"  generic classification: {data.get('m_eff2_classification_generic')}",
        f"  dispersion: {data.get('dispersion')}",
        "",
        "Stress-energy:",
        str(data.get("stress_energy")),
        f"  definition: {data.get('stress_energy_definition')}",
        f"  conservation: {data.get('conservation')}",
        "",
        "Metric field equation:",
        str(data.get("metric_field_equation")),
        f"  equivalent: {data.get('metric_field_equation_equivalent')}",
        "",
        "Energy density:",
        str(data.get("energy_density")),
        "",
        "Weak-field metric response:",
        str(wf.get("sourcing")),
        f"  {wf.get('harmonic_gauge')}",
        f"  amplitude: {wf.get('amplitude')}",
        f"  {wf.get('not_a_slogan')}",
        "",
        "Common origin:",
        f"{data.get('common_origin_objects')}: {data.get('common_origin')}",
        f"  inertial = gravitational: {data.get('inertial_equals_gravitational')}",
        "",
        "Field-redefinition dependence:",
        str(data.get("field_redefinition_dependence")),
        f"  canonical normalization: {data.get('canonical_normalization')}",
        f"  canonical unique dynamics: {data.get('canonical_unique_dynamics')}",
        "",
        "Free parameters:",
        str(data.get("free_parameters")),
        "",
        "Unique relation:",
        str(data.get("unique_relation")),
        "",
        "Massless mode:",
        f"  classification: {a.get('classification')}",
        f"  m_eff2: {a.get('m_eff2')}",
        f"  wave T_00 identically zero: {a.get('T00_wave_zero')}",
        "",
        "Massive mode:",
        f"  classification: {b.get('classification')}",
        f"  m_eff2: {b.get('m_eff2')}",
        f"  wave T_00 identically zero: {b.get('T00_wave_zero')}",
        "",
        "Gravitational sourcing:",
        str(data.get("gravitational_sourcing")),
        "",
        "G:",
        str(data.get("G")),
        "",
        "Lambda:",
        str(data.get("Lambda")),
        "",
        "Coefficients:",
        table(["name", "dimension", "provenance", "kind"], data.get("coefficients") or []),
        "",
        "More predictive than previous phases:",
        str(data.get("more_predictive")),
        "",
        "Quantum unitarity:",
        str(data.get("quantum_unitarity")),
        "",
        "Full DOF:",
        str(data.get("full_dof_count")),
        "",
        data.get("conclusion", ""),
    ]
    return "\n".join(lines)
