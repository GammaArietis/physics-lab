"""Report for spacetime Phase 3 plus signature audit."""

from __future__ import annotations

from physics_lab.core.result import ModelResult
from physics_lab.reporting.formatting import banner, table


def format_spacetime_report(result: ModelResult) -> str:
    data = result.metadata.get("spacetime_analysis")
    if not data:
        return ""
    audit = data.get("signature_audit") or {}
    examples = data.get("examples") or {}
    ex_rows = []
    class_rows = []
    for key in ("L1", "L2", "L3", "L4", "L5"):
        block = examples.get(key) or {}
        ex_rows.append(
            [
                key,
                block.get("eom_order"),
                block.get("ostrogradsky"),
                block.get("classical_ghost"),
                block.get("quantum_unitarity"),
            ]
        )
        class_rows.append(
            [
                key,
                block.get("lorentz_invariant"),
                block.get("local"),
                block.get("legendre_degenerate"),
                block.get("canonicalizable"),
                block.get("free_functions"),
            ]
        )
    crit = data.get("criteria") or []
    dim = data.get("dimensional_table") or []
    cov = data.get("lorentz_vs_covariance") or {}
    ns = data.get("no_scale") or {}
    lines = [
        banner("SPACETIME DYNAMICS TEST — PHASE 3", width=44),
        "",
        "Model:",
        data.get("model", ""),
        "",
        "Background:",
        data.get("background", ""),
        "",
        "Lorentz invariance:",
        data.get("lorentz_invariance", ""),
        "",
        "General covariance:",
        data.get("general_covariance", ""),
        "",
        "Locality:",
        data.get("locality", ""),
        "",
        "Derivative order:",
        data.get("derivative_order", ""),
        "",
        "Canonical kinetic term:",
        f"{data.get('canonical_kinetic_term')} / {data.get('canonical_status')}",
        "",
        "Legendre map:",
        data.get("legendre_map", ""),
        "",
        "Ostrogradsky:",
        data.get("ostrogradsky", ""),
        "",
        "Classical ghost test:",
        data.get("classical_ghost_test", ""),
        "",
        "Quantum unitarity:",
        data.get("quantum_unitarity", ""),
        "",
        "Canonical normalization:",
        data.get("canonical_normalization", ""),
        "",
        "Field redefinition freedom:",
        data.get("field_redefinition_freedom", ""),
        "",
        "Free functions:",
        data.get("free_functions", ""),
        "",
        "Free dimensionless parameters:",
        data.get("free_dimensionless_parameters", ""),
        "",
        "Free dimensionful parameters:",
        data.get("free_dimensionful_parameters", ""),
        "",
        "Unique action:",
        data.get("unique_action", ""),
        "",
        "Unique kinetic structure:",
        data.get("unique_kinetic_structure", ""),
        "",
        "Unique dimensionless constant:",
        data.get("unique_dimensionless", ""),
        "",
        "Lorentz vs general covariance:",
        f"  Minkowski Lorentz: {cov.get('Lorentz invariant on fixed Minkowski background')}",
        f"  Covariant on a metric background: {cov.get('Generally covariant on arbitrary metric background')}",
        f"  difference: {cov.get('difference')}",
        "",
        "First-order class:",
        data.get("first_order_class", ""),
        "",
        "F linear in X:",
        data.get("F_linear_in_X", ""),
        "",
        "Examples:",
        table(["L", "EOM order", "Ostrogradsky", "classical ghost", "Q unitarity"], ex_rows),
        "",
        "Example classification:",
        table(["L", "Lorentz", "local", "Legendre deg.", "canonicalizable", "free functions"], class_rows),
        "",
        "Criteria (not interchangeable):",
        table(["property", "controls", "provenance"], crit),
        "",
        "Dimensional analysis:",
        table(["object", "dimension", "role"], dim),
        "",
        "No-scale branch:",
        f"  {ns.get('first_order')}",
        f"  {ns.get('hidden_scale')}",
        "",
        "Previous 1D modules:",
        data.get("previous_1d_signature", ""),
        "",
        banner("SIGNATURE CONSISTENCY", width=37),
        "",
        "Metric:",
        audit.get("metric", ""),
        "",
        "Signature:",
        audit.get("signature", ""),
        "",
        "X:",
        audit.get("X", ""),
        "",
        "Time-derivative coefficient:",
        audit.get("time_derivative_coefficient", ""),
        "",
        "Hamiltonian kinetic sign:",
        audit.get("hamiltonian_kinetic_sign", ""),
        "",
        "Propagator convention:",
        audit.get("propagator_convention", ""),
        "",
        "Propagator consistency:",
        audit.get("propagator_consistency", ""),
        "",
        "Dispersion relation:",
        audit.get("dispersion_relation", ""),
        "",
        "Ghost criterion:",
        audit.get("ghost_criterion", ""),
        "",
        "m2-sign convention:",
        audit.get("m2_sign_convention", ""),
        "",
        "Signature consistency:",
        audit.get("signature_consistency", ""),
        "",
        "Physical interpretation:",
        data.get("interpretation", "UNTESTED"),
        "",
        "First-derivative Lorentz class:",
        f"  {(data.get('first_derivative_class') or {}).get('general_L')}",
        f"  independent from d_mu phi: {(data.get('first_derivative_class') or {}).get('independent_from_dphi')}",
        f"  other invariants: {(data.get('first_derivative_class') or {}).get('other_invariants')}",
        f"  {(data.get('first_derivative_class') or {}).get('status')}",
        "",
        "L5 audit:",
        f"  higher derivatives in L: {(examples.get('L5') or {}).get('higher_derivative_in_L')}",
        f"  Hessian degenerate: {(examples.get('L5') or {}).get('hessian_degenerate')}",
        f"  EOM higher-order: {(examples.get('L5') or {}).get('eom_higher_order')}",
        f"  Ostrogradsky instability: {(examples.get('L5') or {}).get('ostrogradsky_instability')}",
        f"  IBP: {(examples.get('L5') or {}).get('ibp')}",
        f"  dynamically equivalent: {(examples.get('L5') or {}).get('dynamical_equivalent')}",
        f"  {(examples.get('L5') or {}).get('distinction')}",
        "",
        data.get("conclusion", ""),
        "",
        banner("PHASE 3 STATUS", width=32),
        "",
        "Lorentz-invariant scalar class:",
        f"    {(data.get('phase3_status') or {}).get('Lorentz-invariant scalar class')}",
        "",
        "General covariant background class:",
        f"    {(data.get('phase3_status') or {}).get('General covariant background class')}",
        "",
        "Quadratic kinetic term:",
        f"    {(data.get('phase3_status') or {}).get('Quadratic kinetic term')}",
        "",
        "L5 classification:",
        f"    {(data.get('phase3_status') or {}).get('L5 classification')}",
        "",
        "Quantum unitarity:",
        f"    {(data.get('phase3_status') or {}).get('Quantum unitarity')}",
        "",
        "Dynamical gravity:",
        f"    {(data.get('phase3_status') or {}).get('Dynamical gravity')}",
        "",
        "Phase 3:",
        f"    {(data.get('phase3_status') or {}).get('Phase 3')}",
    ]
    return "\n".join(lines)
