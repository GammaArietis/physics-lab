"""Report for Phase 4A dynamical metric test."""

from __future__ import annotations

from physics_lab.core.result import ModelResult
from physics_lab.reporting.formatting import banner, table


def format_dynamical_metric_report(result: ModelResult) -> str:
    data = result.metadata.get("dynamical_metric_analysis")
    if not data:
        return ""
    eom = data.get("equation_order") or {}
    lines = [
        banner("PHASE 4A — DYNAMICAL METRIC TEST", width=44),
        "",
        "Spacetime dimension:",
        str(data.get("spacetime_dimension")),
        "",
        "Dynamical field:",
        str(data.get("dynamical_field")),
        "",
        "Signature:",
        str(data.get("signature")),
        "",
        "Principles:",
        table(["principle", "content", "provenance"], data.get("principles") or []),
        "",
        "General covariant local action:",
        "S[g] = integral d^4x sqrt(-g) L(g, partial g, partial^2 g, ... )  with L a scalar",
        "",
        "Curvature invariants:",
        table(["object", "class", "role"], data.get("curvature_invariants") or []),
        "",
        "Lowest-curvature action:",
        str(data.get("lowest_curvature_action")),
        "",
        "Curvature-squared action:",
        str(data.get("curvature_squared_action")),
        "",
        "Gauss-Bonnet:",
        str(data.get("gauss_bonnet")),
        "",
        "Equation order:",
        f"  linear action highest derivative: {eom.get('linear_action_highest_derivative')}",
        f"  linear EOM: {eom.get('linear_EOM')}",
        f"  quadratic action highest derivative: {eom.get('quadratic_action_highest_derivative')}",
        f"  quadratic EOM: {eom.get('quadratic_EOM')}",
        f"  gauss_bonnet EOM contribution: {eom.get('gauss_bonnet_EOM')}",
        f"  {eom.get('note')}",
        "",
        "Second-order EOM branch:",
        str(data.get("second_order_EOM_branch")),
        "",
        "Independent coefficients:",
        str(data.get("independent_coefficients")),
        "",
        "Independent dimensionless ratios:",
        str(data.get("independent_dimensionless_ratios")),
        "",
        "Einstein-Hilbert:",
        str(data.get("einstein_hilbert")),
        "",
        "Cosmological term:",
        str(data.get("cosmological_term")),
        "",
        "Newton normalization:",
        str(data.get("newton_normalization")),
        "",
        "Ghost/Ostrogradsky:",
        str(data.get("ghost_ostrogradsky")),
        "",
        "Quantum unitarity:",
        str(data.get("quantum_unitarity")),
        "",
        "Unique action:",
        str(data.get("unique_action")),
        "",
        "Unique coefficients:",
        str(data.get("unique_coefficients")),
        "",
        "Unique equations:",
        str(data.get("unique_equations")),
        "",
        "Coefficients:",
        table(["name", "dimension", "provenance", "kind"], data.get("coefficients") or []),
        "",
        "Physical interpretation:",
        data.get("interpretation", "UNTESTED"),
        "",
        data.get("conclusion", ""),
        "",
        banner("PHASE 4A — GENERAL METRIC DYNAMICS AUDIT", width=48),
        "",
        "Previously tested:",
        "FLRW",
        "Bianchi-I",
        "",
        "General theorem benchmark:",
        "Lovelock",
        "",
        "Assumptions required:",
        table(["hypothesis", "status", "where", "role"], (data.get("lovelock_audit") or {}).get("assumptions") or []),
        "",
        "Already present:",
        "\n".join("  " + x for x in ((data.get("lovelock_audit") or {}).get("already_present") or [])),
        "",
        "Additional assumptions:",
        "\n".join("  " + x for x in ((data.get("lovelock_audit") or {}).get("additional_assumptions") or [])),
        "",
        "4D Lovelock terms:",
        str(((data.get("lovelock_audit") or {}).get("d4") or {}).get("allowed_action")),
        f"  k=0: {((data.get('lovelock_audit') or {}).get('d4') or {}).get('k0')}",
        f"  k=1: {((data.get('lovelock_audit') or {}).get('d4') or {}).get('k1')}",
        f"  k=2: {((data.get('lovelock_audit') or {}).get('d4') or {}).get('k2')}",
        f"  k=3: {((data.get('lovelock_audit') or {}).get('d4') or {}).get('k3')}",
        "",
        "Einstein-Hilbert:",
        str(data.get("einstein_hilbert")),
        "",
        "Cosmological term:",
        str(((data.get("lovelock_audit") or {}).get("cosmological_term") or data.get("cosmological_term"))),
        "",
        "Gauss-Bonnet:",
        str((data.get("lovelock_audit") or {}).get("gauss_bonnet_general")),
        "",
        "Higher Lovelock terms:",
        str((data.get("lovelock_audit") or {}).get("higher_lovelock")),
        "",
        "Second-order EOM:",
        str(data.get("second_order_EOM_branch")),
        "",
        "General validity:",
        str((data.get("lovelock_audit") or {}).get("general_validity")),
        "",
        "Unique action basis:",
        str(data.get("unique_action_basis")),
        "",
        "Unique local equation tensor:",
        str(data.get("unique_local_equation_tensor")),
        "",
        "Unique coefficients:",
        str(data.get("unique_coefficients")),
        "",
        "Unique physical theory:",
        str(data.get("unique_physical_theory")),
        "",
        "G:",
        str(data.get("G")),
        "",
        "Lambda:",
        str(data.get("Lambda")),
        "",
        "Quantum unitarity:",
        str(data.get("quantum_unitarity")),
        "",
        "Full DOF:",
        str(data.get("full_dof_count")),
        "",
        "Proof levels:",
        table(["claim", "level", "limit"], (data.get("lovelock_audit") or {}).get("proof_levels") or []),
        "",
        "Dimension scan (D / local k / topological k / GB slot):",
        table(["D", "local", "topological", "GB slot"], (data.get("lovelock_audit") or {}).get("dimension_scan") or []),
        "",
        (data.get("lovelock_audit") or {}).get("implementation_claim", ""),
    ]
    return "\n".join(lines)
