def _resolve(path: str) -> Path:
    candidate = Path(path)
    if candidate.exists():
        return candidate
    root = Path(__file__).resolve().parents[2]
    alt = root / path
    if alt.exists():
        return alt
    raise FileNotFoundError(f"Config not found: {path}")


def cmd_validate(path: str) -> int:
    model = load_model(_resolve(path))
    report = validate(model)
    print(report.text)
    return 0


def cmd_audit(path: str) -> int:
    model = load_model(_resolve(path))
    result = model.solve()
    audit = audit_parameters(model, result)
    print(format_audit(audit))
    return 0


def cmd_spectrum(path: str, plot: str | None = None) -> int:
    model = load_model(_resolve(path))
    result = model.solve()
    print(format_spectrum(result))
    if plot:
        from physics_lab.reporting.plotting import plot_spectrum

        fig = plot_spectrum(result, plot)
        import matplotlib.pyplot as plt

        plt.close(fig)
        print(f"wrote {plot}")
    return 0


