def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="physics_lab",
        description="Physics Model Laboratory — test speculative models without cheating.",
    )
    sub = parser.add_subparsers(dest="command", required=True)
    for name, help_text in (
        ("validate", "Solve the model and print the validation report."),
        ("audit", "Print the parameter audit."),
        ("spectrum", "Print the internal spectrum."),
        ("explore", "Internal-structure exploration report (S¹+C3)."),
    ):
        p = sub.add_parser(name, help=help_text)
        p.add_argument("config", help="YAML or JSON model configuration.")
    sub.choices["spectrum"].add_argument(
        "--plot",
        metavar="PATH",
        help="Optional path to save a spectrum plot (PNG).",
    )
    cmp = sub.add_parser("compare", help="Compare two models (mathematical differences only).")
    cmp.add_argument("config_a", help="MODEL A config (S¹).")
    cmp.add_argument("config_b", help="MODEL B config (S¹+C3).")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "validate":
            return cmd_validate(args.config)
        if args.command == "audit":
            return cmd_audit(args.config)
        if args.command == "spectrum":
            return cmd_spectrum(args.config, plot=getattr(args, "plot", None))
        if args.command == "explore":
            return cmd_explore(args.config)
        if args.command == "compare":
            return cmd_compare(args.config_a, args.config_b)
    except Exception as exc:  # noqa: BLE001 — CLI must show a readable error
        print(f"error: {exc}", file=sys.stderr)
        return 1
    parser.error(f"unknown command {args.command}")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
